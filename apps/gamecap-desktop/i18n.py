def language() -> str:
    return _LANG


def set_language(code: object) -> str:
    global _LANG
    wanted = str(code or "es")
    _LANG = wanted if any(key == wanted for key, _name in LANGUAGES) else "es"
    return _LANG


def language_name(code: str) -> str:
    for key, name in LANGUAGES:
        if key == code:
            return name
    return "Español"


def t(key: str, **fmt: object) -> str:
    table = EN if _LANG == "en" else ES
    text = table.get(key) or ES.get(key) or key
    if not fmt:
        return text
    try:
        return text.format(**fmt)
    except (KeyError, IndexError, ValueError):
        return text
